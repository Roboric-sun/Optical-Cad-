#include "optics/model.hpp"
#include <stdexcept>
using namespace optics;
size_t coordinateChecks() {
    size_t count=0;auto check=[&](bool ok,const char* msg){++count;if(!ok)throw std::runtime_error(msg);};
    auto near=[&](double a,double b,double eps,const char* msg){check(std::isfinite(a)&&std::abs(a-b)<eps,msg);};
    auto vec=[&](Vec3 a,Vec3 b,double eps,const char* msg){near((a-b).norm(),0,eps,msg);};
    auto rejects=[&](auto fn,const char* msg){bool failed=false;try{fn();}catch(const std::exception&){failed=true;}check(failed,msg);};
    const auto rx=RigidFrame::fromPose({{1,2,3},{90,0,0}}),ry=RigidFrame::fromPose({{0,0,0},{0,90,0}});
    vec(rx.world({0,1,0}),{1,2,4},1e-12,"Rigid frame applies rotation and translation");
    vec(rx.local(rx.world({3,-2,1})),{3,-2,1},1e-12,"Rigid frame inverse recovers local point");
    vec(rx.compose(ry).rotate({0,0,1}),{1,0,0},1e-12,"Composed rotations use local axes");
    check((rx.compose(ry).rotate({0,0,1})-ry.compose(rx).rotate({0,0,1})).norm()>.5,"Rotation composition is noncommutative");
    Catalog c;SequentialSystem s;s.surfaces={Surface{},Surface{},Surface{}};s.surfaces[0].thickness=10;s.surfaces[1].thickness=20;s.surfaces[2].thickness=5;
    s.fields={{0,0,1}};s.wavelengths={{.55,1}};s.primary=0;s.pupilDiameter=2;
    auto& cb=s.surfaces[0].coordinates;cb.mode=CoordinateMode::Relative;cb.shift={1,0,0};cb.tilt={0,90,0};
    auto frames=sequentialFrames(s);vec(frames.nominal[0].position,{1,0,0},1e-12,"Translate then tilt preserves parent-frame shift");
    vec(frames.nominal[1].position,{11,0,0},1e-12,"Axial spacing follows rotated local Z");
    vec(frames.image.position,{36,0,0},1e-12,"Image frame inherits local axial spacing");
    cb.order=CoordinateOrder::TiltThenTranslate;frames=sequentialFrames(s);
    vec(frames.nominal[0].position,{0,0,-1},1e-12,"Tilt then translate rotates shift vector");
    auto& back=s.surfaces[2].coordinates;back.mode=CoordinateMode::ReturnOrientation;back.reference=-1;
    frames=sequentialFrames(s);vec(frames.nominal[2].position,{30,0,-1},1e-12,"Orientation return preserves current vertex");
    vec(frames.nominal[2].basis[2],{0,0,1},1e-12,"Orientation return restores global axis");
    back.mode=CoordinateMode::ReturnFrame;back.reference=0;back.shift={0,0,2};
    frames=sequentialFrames(s);vec(frames.nominal[2].position,{2,0,-1},1e-12,"Full return restores earlier frame before local offset");
    back.reference=2;rejects([&]{sequentialFrames(s);},"Self-referential coordinate return rejected");
    check(!s.validate(c).empty(),"Invalid coordinate reference participates in model validation");
    const auto invalid=trace(s,c,{{0,0,-30},{0,0,1},.55});check(invalid.status==TraceStatus::Invalid,"Public trace returns Invalid for bad coordinate metadata");
    back.reference=0;
    auto shifted=s;shifted.surfaces.insert(shifted.surfaces.begin(),Surface{});
    reindexSolves(shifted,{1,2,3,4},c);check(shifted.surfaces[3].coordinates.reference==1,"Insertion reindexes coordinate return references");
    auto removed=s;removed.surfaces.erase(removed.surfaces.begin());
    rejects([&]{reindexSolves(removed,{SIZE_MAX,0,1,2},c);},"Deleting a coordinate reference is rejected transactionally");
    // Exact mirror: z=y, axial input reflects into +Y, screen at Y=20, image at Y=40.
    SequentialSystem folded;Surface mirror;mirror.kind=SurfaceKind::Mirror;mirror.radius=0;mirror.tilt={45,0,0};mirror.thickness=0;
    Surface screen;screen.kind=SurfaceKind::Stop;screen.coordinates.mode=CoordinateMode::Relative;
    screen.coordinates.shift={0,20,0};screen.coordinates.tilt={-90,0,0};screen.thickness=20;
    folded.surfaces={mirror,screen};folded.fields={{0,0,1}};folded.wavelengths={{.55,1}};folded.primary=0;folded.stop=0;folded.pupilDiameter=2;
    check(folded.validate(c).empty(),"Folded mirror geometry validates");
    const auto path=trace(folded,c,{{0,0,-10},{0,0,1},.55});
    check(path.status==TraceStatus::Complete,"Folded ray reaches local image instead of world Z plane");
    vec(path.exitDirection,{0,1,0},1e-12,"45 degree mirror obeys analytic reflected direction");
    vec(path.points[1],{0,0,0},1e-12,"Mirror hit matches analytic plane intersection");
    vec(path.points[2],{0,20,0},1e-11,"Downstream surface hit uses inherited frame");
    vec(path.image,{0,40,0},1e-11,"Folded world image point matches independent geometry");
    vec(path.imageLocal,{0,0,0},1e-11,"Image-local coordinates use the receiver plane");
    near(path.opl,30,1e-10,"OPL uses physical distances through last optical surface");
    const auto aim=pupilRay(folded,c,{},.55,.25,-.5);const auto aimed=trace(folded,c,aim,false,folded.stop,false);
    const auto stop=sequentialFrames(folded).surfaces[0].local(aimed.exitPoint);
    vec(stop,{.25,-.5,0},1e-7,"Pupil aiming targets the true local STOP footprint");
    auto unvignetted=folded;unvignetted.surfaces[1].semiDiameter=.01;
    check(trace(unvignetted,c,pupilRay(unvignetted,c,{},.55,.8,0)).status==TraceStatus::Vignetted,"Local apertures reject physically blocked folded rays");
    const auto sp=spot(folded,c,{},9);check(sp.samples.size()==49,"Folded spot retains all sampled rays");
    for(const auto& sample:sp.samples)near(sample.image.z,0,1e-10,"Folded spot samples lie in local image XY plane");
    const auto first=differentialFirstOrder(folded,c,.55);
    near(first.matrix[0],1,1e-7,"Mirror X height transfer matches analytic plane map");
    near(first.matrix[5],-1,1e-7,"Mirror local Y parity matches analytic map");
    near(first.matrix[15],-1,1e-7,"Mirror Y angular transfer matches reflection");
    check(first.afocal,"Flat folded mirror is correctly classified as afocal");
    const auto tighter=differentialFirstOrder(folded,c,.55,5e-6);
    for(size_t i=0;i<16;++i)near(first.matrix[i],tighter.matrix[i],1e-6,"Differential matrix converges when step is halved");
    SequentialSystem negative;negative.surfaces={Surface{}};negative.surfaces[0].thickness=10;
    negative.surfaces[0].coordinates.mode=CoordinateMode::Relative;negative.surfaces[0].coordinates.shift.z=-100;
    negative.fields={{0,0,1}};negative.wavelengths={{.55,1}};negative.primary=0;negative.pupilDiameter=2;
    const auto negativePath=trace(negative,c,pupilRay(negative,c,{},.55,0,0));
    check(negativePath.status==TraceStatus::Complete,"Negative global component Z chooses a valid entrance launch plane");
    near(negativePath.image.z,-90,1e-8,"Negative-position system reaches its actual world image");
    near(differentialFirstOrder(negative,c,.55).matrix[2],-90,1e-5,"First order retains the specified z=0 input reference plane for negative-position optics");
    auto lens=SequentialSystem::demo();const auto p=paraxial(lens,c,.5875618);
    const auto d=differentialFirstOrder(lens,c,.5875618);
    near(d.matrix[0],p.matrix[0]+lens.surfaces.back().thickness*p.matrix[2],1e-6,"Differential A matches independent reduced-angle ABCD with image translation");
    near(d.matrix[2],p.matrix[1]+lens.surfaces.back().thickness*p.matrix[3],1e-5,"Differential B matches Gaussian propagation");
    near(d.matrix[8],p.matrix[2],1e-7,"Differential power matches Gaussian C");
    near(d.matrix[10],p.matrix[3],1e-6,"Differential D matches Gaussian angular transfer");
    rejects([&]{folded.imageZ();},"Folded system cannot masquerade as a scalar world image Z");
    rejects([&]{paraxial(folded,c,.55);},"Legacy scalar EFL does not silently ignore coordinate breaks");
    rejects([&]{wavefront(folded,c,{},9);},"Unvalidated folded OPD explicitly rejects instead of returning a misleading result");
    rejects([&]{polychromaticDiffraction(folded,c,{},64,33);},"Unvalidated folded diffraction explicitly rejects");
    rejects([&]{autofocus(folded,c);},"Legacy global-Z autofocus rejects folded systems");
    return count;
}
